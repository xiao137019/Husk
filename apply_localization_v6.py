def main(root):
    root = root or "."
    changed = 0
    hits = 0
    if not os.path.isdir(os.path.join(root, "src", "app")):
        print("未找到 src/app 目录，请确认在 Husk 仓库根目录运行。")
        return 1
    for dirpath, _, files in os.walk(os.path.join(root, "src", "app")):
        for fn in files:
            if not fn.endswith(".swift"):
                continue
            path = os.path.join(dirpath, fn)
            src = open(path, encoding="utf-8").read()
            new = src
            for en, zh in TR.items():
                # 用 lambda 作为 repl，避免 re.sub 把值中的字面 \\n(反斜杠+n) 解释成换行符，
                # 从而破坏 Swift 字符串字面量。
                new2 = re.sub('"' + re.escape(en) + '"', lambda m: '"' + zh + '"', new)
                if new2 != new:
                    hits += 1
                    new = new2
            if new != src:
                open(path, "w", encoding="utf-8").write(new)
                changed += 1
                print(f"[替换] {path}")
    print(f"\n完成：修改 {changed} 个文件，执行 {hits} 处替换。")
    return 0

if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else None))
